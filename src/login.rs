//! X offers cross-device Passkey QR through its real browser, not an App QR endpoint.
use serde_json::{Value, json};
use std::{
    process::Command,
    time::{Duration, Instant},
};
use x_api::web::WebBackend;
fn verified() -> Option<Value> {
    WebBackend::new().ok()?.native_me().ok()
}
fn launch(
    command: &mut Command,
    detached: bool,
) -> Result<Option<std::process::Child>, Box<dyn std::error::Error>> {
    if detached {
        return Ok(Some(command.spawn()?));
    }
    if !command.status()?.success() {
        return Err(
            "Cannot open Chrome; open https://x.com/i/flow/login in a supported Chromium browser"
                .into(),
        );
    }
    Ok(None)
}
fn open_login() -> Result<(), Box<dyn std::error::Error>> {
    #[cfg(target_os = "macos")]
    let mut command = {
        let mut c = Command::new("open");
        c.args(["-a", "Google Chrome", "https://x.com/i/flow/login"]);
        c
    };
    #[cfg(target_os = "windows")]
    let mut command = {
        let mut c = Command::new("cmd");
        c.args(["/C", "start", "", "chrome", "https://x.com/i/flow/login"]);
        c
    };
    #[cfg(not(any(target_os = "macos", target_os = "windows")))]
    let mut command = {
        let mut c = Command::new("google-chrome");
        c.arg("https://x.com/i/flow/login");
        c
    };
    launch(
        &mut command,
        cfg!(not(any(target_os = "macos", target_os = "windows"))),
    )?;
    Ok(())
}
pub(crate) fn run(qr: bool, timeout: u64) -> Result<Value, Box<dyn std::error::Error>> {
    if !(1..=600).contains(&timeout) {
        return Err("timeout must be 1..600 seconds".into());
    }
    if let Some(profile) = verified() {
        return Ok(json!({"is_login":true,"reused_browser_session":true,"profile":profile}));
    }
    if qr {
        eprintln!(
            "X has no native App-scan QR login endpoint. In the official browser choose Passkey, then a nearby/another device if offered. Its QR is generated by the browser/OS. An enrolled Passkey and a compatible device are required; otherwise use the browser's normal login. The CLI does not fabricate a QR or collect your password."
        );
    }
    open_login()?;
    let until = Instant::now() + Duration::from_secs(timeout);
    while Instant::now() < until {
        std::thread::sleep(Duration::from_secs(3));
        if let Some(profile) = verified() {
            return Ok(
                json!({"is_login":true,"login_method":"official_browser","profile":profile}),
            );
        }
    }
    Err(
        "Browser login timed out or no supported browser session was found; no session modified"
            .into(),
    )
}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    #[test]
    fn detached_browser_does_not_block_login_polling() {
        let now = Instant::now();
        let mut command = Command::new("sh");
        command.args(["-c", "sleep 2"]);
        let child = launch(&mut command, true).unwrap();
        assert!(
            now.elapsed() < Duration::from_secs(1),
            "browser lifetime blocked polling"
        );
        let mut child = child.expect("detached child handle");
        let _ = child.kill();
        let _ = child.wait();
    }
}
